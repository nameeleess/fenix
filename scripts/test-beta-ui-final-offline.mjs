import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:390,height:844}})
let page=await context.newPage()
const origin='http://127.0.0.1:4180'
try {
  await page.goto(origin)
  await page.getByRole('heading',{name:'HOME',exact:true}).waitFor()
  await page.evaluate(()=>navigator.serviceWorker.ready.then(()=>true))
  await page.reload()
  await page.waitForFunction(()=>navigator.serviceWorker.controller!==null)
  await page.getByRole('button',{name:'Abrir Settings',exact:true}).click()
  await page.locator('input[type=file]').setInputFiles('../../outputs/ot05-synthetic-backup.json')
  await page.getByText(/Backup validado:/).waitFor()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Restaurar backup validado'}).click()
  await page.getByRole('heading',{name:'HOME',exact:true}).waitFor()
  await page.getByRole('button',{name:'Training',exact:true}).click()
  await page.getByRole('button',{name:'Iniciar QA routine',exact:true}).click()
  const row=page.locator('.training-set-row:not(.is-warmup)').first()
  await row.locator('input').nth(0).fill('15.125')
  await row.locator('input').nth(1).fill('8')
  await row.locator('input').nth(2).fill('2')
  await row.getByRole('button',{name:'Guardar',exact:true}).click()
  await row.getByRole('button',{name:'Guardar',exact:true}).waitFor({state:'visible'})
  await page.waitForFunction(()=>!document.querySelector('.training-set-row:not(.is-warmup) button')?.disabled)
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('heading',{name:'HOME',exact:true}).waitFor()
  await page.getByRole('button',{name:'Training',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.training-set-row:not(.is-warmup) input')?.value==='15.125')
  await page.close()
  page=await context.newPage()
  await page.goto(origin)
  await page.getByRole('heading',{name:'HOME',exact:true}).waitFor()
  await page.getByRole('button',{name:'Training',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.training-set-row:not(.is-warmup) input')?.value==='15.125')
  await page.screenshot({path:process.env.BETA_OFFLINE_SCREENSHOT || '../../outputs/ot05-offline-active.png',fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Active session horizontal overflow')
  for(const button of await page.locator('.training-set-row:not(.is-warmup)').first().locator(':scope > button').all()) {
    const box=await button.boundingBox()
    assert.ok(box && box.x>=0 && box.x+box.width<=390,'Working set action clipped')
  }
  assert.equal(await page.evaluate(async()=>{try {await fetch('/offline-network-probe-'+crypto.randomUUID(),{cache:'no-store'});return false}catch{return true}}),true,'Uncached network request must fail')
  console.log('PASS production build: Settings synthetic restore, service worker controlled; offline reload and tab reopen retain active session and 15.125kg saved working-set draft. Chromium mobile 390x844; physical iPhone NOT_RUN.')
} finally {await browser.close()}

